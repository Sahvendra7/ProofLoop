from fastapi import APIRouter, UploadFile, File, HTTPException, Form
from typing import Dict
from datetime import datetime
import uuid

from app.models.schemas import ScanResult, RecommendationResponse, Baseline, ProgressComparison, SkinMeasurements
from app.services.youcam import youcam_service
from app.services.recommendation import generate_recommendations

router = APIRouter()

# In-memory storage for MVP. In a real app, use PostgreSQL/SQLite.
scans_db: Dict[str, ScanResult] = {}
baselines_db: Dict[str, Baseline] = {}

@router.post("/scan", response_model=ScanResult)
async def analyze_skin(image: UploadFile = File(...)):
    if not image.content_type.startswith("image/"):
        raise HTTPException(status_code=400, detail="File must be an image.")
    
    contents = await image.read()
    try:
        result = await youcam_service.analyze_skin(contents)
        scans_db[result.id] = result
        return result
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@router.get("/recommendations/{scan_id}", response_model=RecommendationResponse)
async def get_recommendations(scan_id: str, goal: str):
    if scan_id not in scans_db:
        raise HTTPException(status_code=404, detail="Scan not found.")
    
    scan = scans_db[scan_id]
    recommendations = generate_recommendations(scan.measurements, goal)
    
    return RecommendationResponse(
        recommendations=recommendations,
        goal=goal
    )

@router.post("/baseline", response_model=Baseline)
async def save_baseline(scan_id: str = Form(...)):
    if scan_id not in scans_db:
        raise HTTPException(status_code=404, detail="Scan not found.")
    
    scan = scans_db[scan_id]
    baseline_id = str(uuid.uuid4())
    
    baseline = Baseline(
        id=baseline_id,
        scan_id=scan_id,
        measurements=scan.measurements,
        created_at=datetime.utcnow().isoformat()
    )
    
    # For MVP, we tie a single baseline to a "session" or just store it.
    baselines_db["current_user"] = baseline 
    return baseline

@router.get("/journey", response_model=ProgressComparison)
async def get_journey(current_scan_id: str):
    if "current_user" not in baselines_db:
        raise HTTPException(status_code=404, detail="No baseline found. Please save a baseline first.")
        
    if current_scan_id not in scans_db:
        raise HTTPException(status_code=404, detail="Current scan not found.")
        
    baseline = baselines_db["current_user"]
    current_scan = scans_db[current_scan_id]
    
    # Calculate deltas (Positive delta = improvement, negative = regression, assuming lower is better for oiliness, redness, etc.)
    # For the sake of the hackathon demo, we will calculate delta as: Baseline - Current
    # (If baseline redness was 68 and current is 59, delta is +9)
    # Actually, let's just do Current - Baseline and the UI handles interpretation.
    
    deltas = {
        "hydration": current_scan.measurements.hydration - baseline.measurements.hydration,
        "oiliness": current_scan.measurements.oiliness - baseline.measurements.oiliness,
        "redness": current_scan.measurements.redness - baseline.measurements.redness,
        "texture": current_scan.measurements.texture - baseline.measurements.texture,
        "pores": current_scan.measurements.pores - baseline.measurements.pores,
        "acne": current_scan.measurements.acne - baseline.measurements.acne,
        "dark_circles": current_scan.measurements.dark_circles - baseline.measurements.dark_circles,
    }
    
    return ProgressComparison(
        baseline=baseline,
        current=current_scan,
        deltas=deltas
    )

@router.post("/demo/journey-jump")
async def demo_journey_jump():
    """
    Hackathon helper: creates a 'Day 21' scan that shows progress compared to the baseline,
    so the judges can see the loop in action without waiting 3 weeks.
    """
    if "current_user" not in baselines_db:
        raise HTTPException(status_code=400, detail="No baseline to jump from.")
        
    baseline = baselines_db["current_user"]
    
    improved_measurements = SkinMeasurements(
        hydration=min(100, baseline.measurements.hydration + 13),
        oiliness=max(0, baseline.measurements.oiliness - 13),
        redness=max(0, baseline.measurements.redness - 9),
        texture=max(0, baseline.measurements.texture - 7),
        pores=baseline.measurements.pores,
        acne=baseline.measurements.acne,
        dark_circles=baseline.measurements.dark_circles
    )
    
    new_scan = ScanResult(
        id=str(uuid.uuid4()),
        measurements=improved_measurements,
        raw_response={"note": "Generated by Demo Journey Jump"},
        is_demo=True
    )
    scans_db[new_scan.id] = new_scan
    
    return {"new_scan_id": new_scan.id}
    
@router.post("/simulate")
async def simulate_skin(image: UploadFile = File(...), feature: str = Form(...), intensity: float = Form(1.0)):
    if not image.content_type.startswith("image/"):
        raise HTTPException(status_code=400, detail="File must be an image.")
    
    contents = await image.read()
    try:
        image_url = await youcam_service.simulate_skin(contents, feature, intensity)
        return {"image_url": image_url}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
